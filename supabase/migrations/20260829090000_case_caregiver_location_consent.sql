-- ============================================================================
-- 간병일지 위치정보 동의 — case_caregivers에 동의 상태 추가
-- ============================================================================
-- [운영 DB 상태 — 2026-08-29] 이 migration은 운영 DB에 적용 완료됐다.
-- 적용 후 두 컬럼 존재(nullable, default 없음)와 기존 행이 전부 null임을
-- 확인했다(건수 변화 없음). 재실행해도 안전하지만(if not exists) 그럴
-- 이유가 없다.
--
-- *** 배경 ***
-- 지금은 간병일지 작성 화면에 들어가는 즉시 navigator.geolocation을 호출해
-- 브라우저 위치 권한 팝업이 뜬다(app/case-care-log/[id]/CareLogClient.tsx의
-- 마운트 useEffect). 위치를 쓴다는 사실을 알리고 동의를 받는 절차가 앞에
-- 없다.
--
-- 앞으로는 "이 간병인이 이 사례에서 처음 간병일지를 쓸 때" 한 번만 묻고,
-- 그 선택을 기억한다. 매 일지마다 다시 묻지 않는다.
--
-- *** 왜 case_caregivers인가 ***
-- 동의 범위가 정확히 (case_id, caregiver_id) 쌍이다. case_caregivers는 이미
-- 그 쌍을 표현하는 연결 테이블이고, 간병일지 화면이 통과하는
-- requireCurrentCaregiverSession()이 이 행을 이미 조회해 반환한다
-- (lib/caregiver-auth.ts 133행) — 새 테이블을 만들면 같은 쌍을 담은 테이블이
-- 둘로 늘고 조회도 한 번 더 늘 뿐이라, 신규 테이블을 만들지 않는다.
--
-- 동의를 care_logs(일지 행)에 두지 않는 이유도 같다 — 동의는 일지 1건이
-- 아니라 "그 사례에서의 간병인" 단위 사실이라, 일지마다 복제하면 같은 값이
-- 행 수만큼 중복되고 서로 어긋날 수 있다. 일지에는 지금처럼 그때의 위치
-- '결과'(location_status/좌표/실패사유)만 남긴다.
--
-- *** 가족간병인 ***
-- case_caregivers는 간병인마다 별도 행이므로, 같은 사례라도 간병인 A의
-- 동의가 가족간병인 B에게 상속되지 않는다. B는 그 사례에서 처음 일지를 쓸 때
-- 자기 행이 null이라 다시 한 번 질문을 받는다. 현재 간병인이 바뀌어도 판단
-- 기준은 언제나 "지금 로그인한 간병인의 행"이다.
--
-- *** 이 파일이 하지 않는 것 ***
--   - 기존 행을 backfill하지 않는다(전부 null로 남는다 = 아직 답하지 않음).
--   - care_logs를 건드리지 않는다.
--   - 신규 테이블을 만들지 않는다.
--   - 기존 컬럼/제약/RLS를 바꾸지 않는다.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 컬럼 추가
-- ----------------------------------------------------------------------------
-- location_consent
--   null  = 아직 최초 질문에 답하지 않음(질문을 보여줘야 하는 상태)
--   true  = 동의함 → 이후 일지 작성 시 위치 확인을 시도한다
--   false = 동의하지 않음 → 이후 geolocation을 호출하지 않는다
--
-- 기본값을 두지 않는다. false를 기본값으로 잡으면 "거부함"과 "아직 안 물어봄"이
-- 구분되지 않아 질문을 영영 띄울 수 없게 된다.
alter table case_caregivers add column if not exists location_consent boolean;

-- 동의/거부를 선택한 시각. 동의든 거부든 "그 선택을 한 시점"을 남긴다
-- (거부도 사용자의 의사표시이므로 시각을 기록해 두는 편이 감사 추적에
-- 유리하다). location_consent가 null이면 이 값도 null이다.
alter table case_caregivers add column if not exists location_consent_at timestamptz;


-- ----------------------------------------------------------------------------
-- COMMENT
-- ----------------------------------------------------------------------------
comment on column case_caregivers.location_consent is
  '간병일지 작성 시 위치정보 수집·이용 동의. null=아직 묻지 않음(최초 질문 대상), true=동의, false=거부. 동의 범위는 이 행이 나타내는 (case_id, caregiver_id) 조합이며 다른 간병인에게 상속되지 않는다.';

comment on column case_caregivers.location_consent_at is
  '위치정보 동의/거부를 선택한 시각. 동의와 거부 모두 기록한다.';


